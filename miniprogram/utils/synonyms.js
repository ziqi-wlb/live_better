// 词 -> 所在词组（含自身）
const SYN_INDEX = {};
SYNONYM_GROUPS.forEach((group) => {
  group.forEach((word) => {
    SYN_INDEX[word] = group;
  });
});

// 某个词的可匹配集合：自身在前，同义词在后
function alternatives(term) {
  const group = SYN_INDEX[term];
  if (!group) return [term];
  return [term].concat(group.filter((w) => w !== term));
}

// 供高亮用：把查询词展开成「自身 + 同义词」的扁平列表
function expandTerms(terms) {
  const out = [];
  const seen = {};
  terms.forEach((term) => {
    alternatives(term).forEach((w) => {
      if (!seen[w]) {
        seen[w] = true;
        out.push(w);
      }
    });
  });
  return out;
}

module.exports = { SYNONYM_GROUPS, alternatives, expandTerms };
